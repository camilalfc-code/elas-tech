package org.example.Aula08102026;

public class Painel {

    public void exibir(String valor) {
        System.out.println("Recebi uma String: " + valor);
    }

    public void exibir(int valor) {
        System.out.println("Recebi um int: " + valor);
    }

    public void exibir(boolean valor) {
        System.out.println("Recebi um boolean: " + valor);
    }

    public void exibir(double valor) {
        System.out.println("Recebi um double: " + valor);
    }
}
